-- ============================================================
-- Ampliación del catálogo: registro de ventas
-- Nuevas tablas: ventas, detalle_ventas
-- ============================================================

-- --------------------------------------------------------
-- Tabla: ventas (cabecera de cada venta)
-- --------------------------------------------------------
DROP TABLE IF EXISTS `detalle_ventas`;
DROP TABLE IF EXISTS `ventas`;

CREATE TABLE `ventas` (
  `idVenta` int unsigned NOT NULL AUTO_INCREMENT,
  `idCliente` int NOT NULL,
  `fechaVenta` date NOT NULL,
  `monto` decimal(10,2) NOT NULL,
  PRIMARY KEY (`idVenta`),
  KEY `idCliente` (`idCliente`),
  CONSTRAINT `ventas_ibfk_1` FOREIGN KEY (`idCliente`) REFERENCES `clientes` (`idCliente`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- --------------------------------------------------------
-- Tabla: detalle_ventas (productos incluidos en cada venta)
-- --------------------------------------------------------
CREATE TABLE `detalle_ventas` (
  `idDetalleVenta` int unsigned NOT NULL AUTO_INCREMENT,
  `idVenta` int unsigned NOT NULL,
  `idProducto` mediumint unsigned NOT NULL,
  `cantidad` smallint unsigned NOT NULL,
  `precioUnitario` decimal(10,2) NOT NULL,
  PRIMARY KEY (`idDetalleVenta`),
  KEY `idVenta` (`idVenta`),
  KEY `idProducto` (`idProducto`),
  CONSTRAINT `detalle_ventas_ibfk_1` FOREIGN KEY (`idVenta`) REFERENCES `ventas` (`idVenta`),
  CONSTRAINT `detalle_ventas_ibfk_2` FOREIGN KEY (`idProducto`) REFERENCES `productos` (`idProducto`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

